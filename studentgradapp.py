import streamlit as st

GRADE_BOUNDARIES = [(70, "First"), (60, "2:1"), (50, "2:2"), (40, "Third")]

def valid_mark(mark):
    return 0 <= mark <= 100

def average_mark(marks):
    if not marks or any(not valid_mark(m) for m in marks):
        raise ValueError("Marks must be between 0 and 100")
    return round(sum(marks) / len(marks), 2)

def classify(mark):
    if not valid_mark(mark):
        return "Invalid mark"
    for minimum, label in GRADE_BOUNDARIES:
        if mark >= minimum:
            return label
    return "Fail"

def passed(mark):
    return mark >= 40

def highest_mark(marks):
    return max(marks)

def lowest_mark(marks):
    return min(marks)

def class_average(records):
    return round(sum(average_mark(m) for m in records.values()) / len(records), 2)

def pass_count(records):
    return sum(passed(average_mark(m)) for m in records.values())

st.title("Student Grade Management System")
st.write("Enter marks for three modules (0–100).")

name = st.text_input("Student name")
marks = [st.number_input(f"Module {i} mark", min_value=0, max_value=100, value=50, step=1) for i in range(1, 4)]

if "records" not in st.session_state:
    st.session_state.records = {}

if st.button("Save student result"):
    if not name.strip():
        st.error("Enter a student name")
    else:
        st.session_state.records[name.strip()] = marks
        st.success("Student result saved for this session")

if st.session_state.records:
    rows = []
    for student, student_marks in st.session_state.records.items():
        avg = average_mark(student_marks)
        rows.append({
            "Student": student,
            "Average": avg,
            "Classification": classify(avg),
            "Pass": passed(avg),
            "Highest": highest_mark(student_marks),
            "Lowest": lowest_mark(student_marks)
        })
    st.dataframe(rows)
    st.metric("Class average", class_average(st.session_state.records))
    st.metric("Students passed", pass_count(st.session_state.records))
    st.caption("Demo data is stored only in the current Streamlit session.")